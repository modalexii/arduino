#!/usr/bin/env python3
"""Embed a TTF as a C byte array for lv_tiny_ttf_create_data().

Usage (from the project folder; needs `pip install fonttools`):
    python tools/embed_ttf.py NixieOne-Regular.ttf src/fonts/nixie_one_ttf.h nixie_one_ttf

Re-run it after swapping the hour font (CLOCK_PLAN.md §1, open item 2).

The font is cut down to the digits (and space) and its GPOS/GSUB/GDEF/kern tables are
removed. That is not just to save flash: LVGL 9.2's tiny_ttf (stb_truetype_htcw.h,
stbtt_KernTableCheck) forgets to add the GPOS table's offset when it reads the lookup
list, so on any font with a GPOS table it reads a garbage lookup count and walks up to
~160 KB past the end of the font data. Without GPOS/kern the check returns at once.
Kerning is irrelevant for one or two digits; HOUR_LETTER_SPACE adjusts the spacing.
"""
import io
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

KEEP = [0x20] + list(range(0x30, 0x3A))  # space, 0-9
DROP = ["GPOS", "GSUB", "GDEF", "kern"]


def cut_down(path):
    font = TTFont(path)
    opts = subset.Options()
    opts.layout_features = []
    opts.drop_tables += DROP
    opts.hinting = False          # stb_truetype ignores hinting
    opts.name_IDs = ["*"]         # keep the name table (licence/copyright) intact
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=KEEP)
    sub.subset(font)
    for t in DROP:
        assert t not in font, t
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src, dst, name = sys.argv[1:]
    data = cut_down(src)
    lines = [
        f"// {os.path.basename(dst)}: {os.path.basename(src)} embedded for lv_tiny_ttf_create_data().",
        f"// Generated by tools/embed_ttf.py; do not edit. Digits and space only, no GPOS/GSUB/GDEF/kern",
        f"// (see the tool for why). {len(data)} bytes.",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f"static const uint8_t {name}[] = {{",
    ]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines += ["};", f"static const size_t {name}_len = sizeof({name});", ""]
    with open(dst, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {dst}: {len(data)} bytes as {name}[]")


if __name__ == "__main__":
    main()
