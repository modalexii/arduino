#!/usr/bin/env python3
"""Generate src/tz_table.h (IANA zone name -> POSIX TZ string) for the set-time portal.

Sources (both kept in tools/tzdata/ so the header can be rebuilt offline):
  zones.csv  nayarsystems/posix_tz_db (MIT): "Area/City","POSIX TZ"
  backward   IANA tz database 'backward' file (public domain): old names that
             browsers may still report (e.g. Asia/Calcutta, US/Eastern, Europe/Kiev),
             added as aliases of the zone they link to.

Usage:  python3 tools/gen_tz_table.py            (run from the project folder)
        python3 tools/gen_tz_table.py --download (refresh tools/tzdata/ first)
"""
import csv
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "tzdata")
OUT = os.path.join(HERE, "..", "src", "tz_table.h")
URLS = {
    "zones.csv": "https://raw.githubusercontent.com/nayarsystems/posix_tz_db/master/zones.csv",
    "backward": "https://raw.githubusercontent.com/eggert/tz/main/backward",
}


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if "--download" in sys.argv:
        os.makedirs(DATA, exist_ok=True)
        for name, url in URLS.items():
            print("downloading", url)
            urllib.request.urlretrieve(url, os.path.join(DATA, name))

    zones = {}
    with open(os.path.join(DATA, "zones.csv"), newline="") as f:
        for row in csv.reader(f):
            if len(row) == 2 and row[0] and row[1]:
                zones[row[0]] = row[1]
    n_zones = len(zones)

    aliases = 0
    bpath = os.path.join(DATA, "backward")
    if os.path.exists(bpath):
        with open(bpath) as f:
            for line in f:
                parts = line.split("#")[0].split()
                if len(parts) == 3 and parts[0] == "Link":
                    target, link = parts[1], parts[2]
                    if link not in zones and target in zones:
                        zones[link] = zones[target]
                        aliases += 1

    names = sorted(zones)  # strcmp order (ASCII), for the firmware's binary search
    longest = max(len(v) for v in zones.values())
    with open(OUT, "w", newline="\n") as f:
        f.write("// tz_table.h: IANA -> POSIX TZ map. GENERATED by tools/gen_tz_table.py from\n")
        f.write("// nayarsystems/posix_tz_db zones.csv (MIT) plus aliases from the IANA 'backward'\n")
        f.write("// file. Do not edit by hand. Sorted by name (strcmp order) for binary search.\n")
        f.write("#pragma once\n#include <stddef.h>\n#include <string.h>\n\n")
        f.write("namespace tzdb {\n\n")
        f.write("struct Zone { const char *name; const char *posix; };\n\n")
        f.write(f"// {n_zones} zones + {aliases} aliases; longest POSIX string {longest} chars.\n")
        f.write("constexpr Zone ZONES[] = {\n")
        for n in names:
            f.write(f"  {{{c_str(n)}, {c_str(zones[n])}}},\n")
        f.write("};\n")
        f.write("constexpr size_t ZONE_COUNT = sizeof(ZONES) / sizeof(ZONES[0]);\n\n")
        f.write("// POSIX TZ string for an IANA name, or nullptr if unknown.\n")
        f.write("inline const char *lookup(const char *iana) {\n")
        f.write("  size_t lo = 0, hi = ZONE_COUNT;\n")
        f.write("  while (lo < hi) {\n")
        f.write("    size_t mid = (lo + hi) / 2;\n")
        f.write("    int c = strcmp(iana, ZONES[mid].name);\n")
        f.write("    if (c == 0) return ZONES[mid].posix;\n")
        f.write("    if (c < 0) hi = mid; else lo = mid + 1;\n")
        f.write("  }\n  return nullptr;\n}\n\n}  // namespace tzdb\n")
    print(f"wrote {os.path.normpath(OUT)}: {n_zones} zones + {aliases} aliases")


if __name__ == "__main__":
    main()
